#!/usr/bin/env python3
"""Build the UI's signed-distance-field font (milestone 17).

Renders printable ASCII (32..126) of a TrueType/OpenType font at 8x the
cell size, computes each output pixel's signed distance to the glyph's
outline (numpy, nearest edge pixel), and writes:
  assets/fonts/ui_sdf.png   grey atlas, 16 columns of CELL x CELL cells;
                            128 = on the outline, brighter = inside,
                            SPREAD pixels of distance on each side
  assets/fonts/ui_sdf.cfg   metrics in the data-file format (DATA_FORMAT.md)
Usage: tools/make_sdf_font.py [font file]   (default: Inter SemiBold)
"""
import sys, os
import numpy as np
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"
CELL = 48          # atlas cell (pixels)
EM = 34            # font size in the atlas (pixels per em)
SPREAD = 6.0       # distance range each side of the outline (atlas pixels)
SCALE = 8          # supersampling for the distance search
COLS = 16
FIRST, LAST = 32, 126

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
font = ImageFont.truetype(FONT, EM * SCALE)
ascent, descent = font.getmetrics()
n = LAST - FIRST + 1
rows = (n + COLS - 1) // COLS
atlas = np.zeros((rows * CELL, COLS * CELL), np.uint8)
lines = ["# UI font metrics (generated by tools/make_sdf_font.py; do not edit).",
         "# Units: atlas pixels at em = %d. glyph_<code> = advance, x0, y0, x1, y1" % EM,
         "# (the glyph's box in its cell, relative to the pen on the baseline;",
         "# y grows down).",
         "cell = %d" % CELL, "em = %d" % EM, "spread = %g" % SPREAD,
         "ascent = %.3f" % (ascent / SCALE), "descent = %.3f" % (descent / SCALE),
         "columns = %d" % COLS, "first = %d" % FIRST, "count = %d" % n]

# pen position inside a cell (atlas pixels): leave SPREAD around the glyph
PEN_X, BASE_Y = 8, 36
for i, code in enumerate(range(FIRST, LAST + 1)):
    ch = chr(code)
    adv = font.getlength(ch) / SCALE
    big = Image.new("L", (CELL * SCALE, CELL * SCALE), 0)
    ImageDraw.Draw(big).text((PEN_X * SCALE, BASE_Y * SCALE), ch, font=font, fill=255, anchor="ls")
    m = np.asarray(big) >= 128
    # edge pixels: inside pixels with an outside 4-neighbour
    pad = np.pad(m, 1)
    edge = m & ~(pad[:-2, 1:-1] & pad[2:, 1:-1] & pad[1:-1, :-2] & pad[1:-1, 2:])
    ey, ex = np.nonzero(edge)
    # output pixel centres in hi-res coordinates
    c = (np.arange(CELL) + 0.5) * SCALE
    oy, ox = np.meshgrid(c, c, indexing="ij")
    if len(ex):
        d2 = np.full(oy.shape, np.inf)
        for k in range(0, len(ex), 2048):
            dx = ox[..., None] - ex[None, None, k:k + 2048]
            dy = oy[..., None] - ey[None, None, k:k + 2048]
            d2 = np.minimum(d2, (dx * dx + dy * dy).min(axis=2))
        dist = np.sqrt(d2) / SCALE
    else:
        dist = np.full(oy.shape, SPREAD)
    inside = m[(oy - 0.5).astype(int), (ox - 0.5).astype(int)]
    sd = np.where(inside, dist, -dist)
    v = np.clip(128 + sd * (127.0 / SPREAD), 0, 255).astype(np.uint8)
    r, col = divmod(i, COLS)
    atlas[r * CELL:(r + 1) * CELL, col * CELL:(col + 1) * CELL] = v
    bb = font.getbbox(ch, anchor="ls")          # hi-res, relative to the pen
    if bb[2] > bb[0]:
        x0, y0, x1, y1 = (bb[0] / SCALE, bb[1] / SCALE, bb[2] / SCALE, bb[3] / SCALE)
    else:
        x0 = y0 = x1 = y1 = 0.0
    lines.append("glyph_%d = %.3f, %.3f, %.3f, %.3f, %.3f" % (code, adv, x0, y0, x1, y1))
lines.append("pen = %d, %d" % (PEN_X, BASE_Y))
Image.fromarray(atlas, "L").save(os.path.join(root, "assets/fonts/ui_sdf.png"))
open(os.path.join(root, "assets/fonts/ui_sdf.cfg"), "w").write("\n".join(lines) + "\n")
print("wrote assets/fonts/ui_sdf.png (%dx%d) and ui_sdf.cfg" % (atlas.shape[1], atlas.shape[0]))
